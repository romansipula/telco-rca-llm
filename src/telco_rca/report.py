"""Markdown tables from the systems manifest (results/systems.json) and their metrics.json files."""
from __future__ import annotations

from pathlib import Path

from .io import read_json


def _f(x, nd=3):
    return "–" if x is None else f"{x:.{nd}f}"


def metrics_path(entry: dict) -> Path:
    if entry.get("metrics"):
        return Path(entry["metrics"])
    return Path(entry["pred"]).with_name("metrics.json")


MAIN_HEAD = ["group", "system", "n", "acc", "macro-F1", "acc excl. Jamming", "KPI set-F1", "JSON valid",
             "schema valid", "grounded KPI mentions"]
TEXT_HEAD = ["system", "expl ROUGE-L", "expl BERTScore F1", "expl BERTScore (rescaled)", "res ROUGE-L",
             "res BERTScore F1", "res BERTScore (rescaled)"]


def tables(manifest: dict) -> tuple[str, str]:
    main = ["| " + " | ".join(MAIN_HEAD) + " |", "|" + "---|" * len(MAIN_HEAD)]
    text = ["| " + " | ".join(TEXT_HEAD) + " |", "|" + "---|" * len(TEXT_HEAD)]
    for name, e in manifest.items():
        if name.startswith("_"):
            continue
        p = metrics_path(e)
        if not p.exists():
            continue
        m = read_json(p)
        rc = m.get("root_cause", {})
        ex = m.get("root_cause_excl_jamming", {})
        gr = m.get("explanation_kpi_grounding", {}).get("mean_fraction_of_mentioned_kpis_that_deviate")
        label_only = e.get("label_only") or "majority" in name
        main.append("| " + " | ".join([
            e.get("group", ""), f"`{name}`", str(m.get("n")), _f(rc.get("accuracy")), _f(rc.get("macro_f1")),
            _f(ex.get("accuracy")), "–" if label_only else _f(m.get("affected_kpis_set_f1")),
            "–" if label_only else _f(m.get("json_valid_rate")),
            "–" if label_only else _f(m.get("schema_valid_rate")), "–" if label_only else _f(gr)]) + " |")
        if "explanation_rougeL" in m:
            eb, rb = m.get("explanation_bertscore", {}), m.get("resolution_bertscore", {})
            text.append("| " + " | ".join([f"`{name}`", _f(m.get("explanation_rougeL")), _f(eb.get("f1")),
                                            _f(eb.get("f1_rescaled")), _f(m.get("resolution_rougeL")),
                                            _f(rb.get("f1")), _f(rb.get("f1_rescaled"))]) + " |")
    return "\n".join(main), "\n".join(text)


def per_class(manifest: dict, systems: list[str]) -> str:
    rows = {}
    for s in systems:
        m = read_json(metrics_path(manifest[s]))
        for lab, f in m["root_cause"]["per_class_f1"].items():
            rows.setdefault(lab, {})[s] = f
    head = ["root cause (test n)"] + [f"`{s}`" for s in systems]
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    first = read_json(metrics_path(manifest[systems[0]]))
    cm = first["root_cause"]["confusion_matrix"]
    n_by = {lab: sum(r) for lab, r in zip(cm["labels"], cm["matrix"])}
    for lab in sorted(rows):
        out.append("| " + " | ".join([f"{lab} ({n_by.get(lab, '?')})"] + [_f(rows[lab].get(s)) for s in systems]) + " |")
    return "\n".join(out)


def report(results_dir: str, out: str, manifest_path: str | None = None) -> str:
    manifest = read_json(manifest_path or Path(results_dir) / "systems.json")
    main, text = tables(manifest)
    md = ("# Results summary (generated by `telco-rca report` from results/systems.json)\n\n"
          "## Root cause, KPIs, JSON\n\n" + main + "\n\n## Explanation / resolution text vs reference tickets\n\n"
          + text + "\n")
    cls = [s for s in ("gb_evidence_features", "gemma4_e4b_sft_hybrid", "ministral3_3b_sft_hybrid",
                       "gemma4_e4b_sft_evidence", "ministral3_3b_sft_evidence") if s in manifest
           and metrics_path(manifest[s]).exists()]
    if cls:
        md += "\n## Per-class F1\n\n" + per_class(manifest, cls) + "\n"
    Path(out).write_text(md)
    print(md)
    return md
