"""Collect ``metrics.json`` files under ``results/`` into markdown tables (results/summary.md)."""
from __future__ import annotations

from pathlib import Path

from .io import read_json


def _f(x, nd=3):
    return "–" if x is None else f"{x:.{nd}f}"


def _row(path: Path, m: dict) -> list[str]:
    rc = m.get("root_cause", {})
    ex = m.get("root_cause_excl_jamming", {})
    eb = m.get("explanation_bertscore", {})
    rb = m.get("resolution_bertscore", {})
    cost = m.get("cost", {}).get("seconds", {})
    return [str(path.parent.relative_to(path.parents[2]) if len(path.parents) > 2 else path.parent),
            str(m.get("n")), _f(rc.get("accuracy")), _f(rc.get("macro_f1")), _f(ex.get("accuracy")),
            _f(m.get("affected_kpis_set_f1")), _f(m.get("json_valid_rate")), _f(m.get("schema_valid_rate")),
            _f(m.get("explanation_rougeL")), _f(eb.get("f1")), _f(m.get("resolution_rougeL")), _f(rb.get("f1")),
            _f(cost.get("mean"), 2)]


HEAD = ["run/system", "n", "acc", "macro-F1", "acc excl. Jamming", "KPI set-F1", "JSON valid", "schema valid",
        "expl ROUGE-L", "expl BERTScore", "res ROUGE-L", "res BERTScore", "s/case"]


def table(paths: list[Path]) -> str:
    lines = ["| " + " | ".join(HEAD) + " |", "|" + "---|" * len(HEAD)]
    for p in paths:
        lines.append("| " + " | ".join(_row(p, read_json(p))) + " |")
    return "\n".join(lines)


def report(results_dir: str, out: str) -> str:
    paths = sorted(Path(results_dir).rglob("metrics.json"))
    md = "# Results summary (generated by `telco-rca report`)\n\n" + table(paths) + "\n"
    Path(out).write_text(md)
    print(md)
    return md
