"""Pick 10 example outputs (5 correct, 5 wrong; spread over classes, seeded) -> markdown.

    python scripts/make_examples.py --pred results/<run>/<system>/predictions.jsonl --out results/examples.md
"""
import argparse
import json
import random
from collections import defaultdict

from telco_rca.io import read_jsonl
from telco_rca.pipeline import load_prepared
from telco_rca.schema import parse_output


def pick(items, k, rng):
    by = defaultdict(list)
    for it in items:
        by[it[0]["root_cause"]].append(it)
    for v in by.values():
        rng.shuffle(v)
    out, keys = [], sorted(by)
    rng.shuffle(keys)
    while len(out) < k and any(by.values()):
        for c in keys:
            if by[c] and len(out) < k:
                out.append(by[c].pop())
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pred", required=True)
    ap.add_argument("--prepared", default="data_cache/prepared/telecomts")
    ap.add_argument("--out", default="results/examples.md")
    ap.add_argument("--seed", type=int, default=3)
    a = ap.parse_args()
    rows, meta = load_prepared(a.prepared)
    by_id = {r["case_id"]: r for r in rows}
    gb = {p["case_id"]: p for p in read_jsonl("results/baseline/gb_probs.jsonl")}
    rng = random.Random(a.seed)
    items = []
    for p in read_jsonl(a.pred):
        r = by_id[p["case_id"]]
        items.append((r, p, parse_output(p["output"], meta["schema"])))
    good = pick([x for x in items if x[2].root_cause == x[0]["root_cause"]], 5, rng)
    bad = pick([x for x in items if x[2].root_cause != x[0]["root_cause"]], 5, rng)
    md = [f"# Example outputs\n\nSystem: `{a.pred}` (5 correct and 5 wrong root causes, seeded pick over classes; "
          "generated by `scripts/make_examples.py`).\n"]
    for title, group in (("Correct", good), ("Wrong", bad)):
        for i, (r, p, po) in enumerate(group, 1):
            md.append(f"## {title} {i}: true = {r['root_cause']}, predicted = {po.root_cause}\n")
            md.append(f"`{r['case_id']}`; schema-valid: {po.schema_ok}\n")
            md.append("<details><summary>evidence block (model input)</summary>\n\n```\n" + r["evidence_text"] +
                      "\n```\n</details>\n")
            if "hybrid" in a.pred:
                top3 = ", ".join(f"{lab} {p_:.2f}" for lab, p_ in gb[r["case_id"]]["top3"])
                md.append(f"GB top-3 in the prompt: {top3}\n")
            out = po.obj if po.obj is not None else p["output"]
            md.append("```json\n" + (json.dumps(out, indent=1, ensure_ascii=False) if isinstance(out, dict) else out)
                      + "\n```\n")
            md.append(f"Reference resolution: _{r['reference_resolution']}_\n")
    open(a.out, "w").write("\n".join(md))
    # compact table for the README
    tab = ["| # | true root cause | predicted | case-specific part of the generated explanation |", "|---|---|---|---|"]
    for title, group in (("ok", good), ("wrong", bad)):
        for i, (r, p, po) in enumerate(group, 1):
            ex = po.explanation.replace("|", "/")
            i0 = ex.find("In this window")
            ex = ex[i0:] if i0 >= 0 else ex
            ex = ex if len(ex) <= 300 else ex[:297] + "..."
            tab.append(f"| {title} {i} | {r['root_cause']} | {po.root_cause} | {ex} |")
    open(a.out.replace(".md", "_table.md"), "w").write("\n".join(tab) + "\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
